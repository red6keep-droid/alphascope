def match(issue_codes, vocab_kinds=()):
    """이슈 코드(방향 포함 'RATES_FED:+') · 사건표 어휘 → 맞는 사슬 id 목록 (앞이 더 맞음)."""
    out = []
    keys = set(issue_codes) | {c.split(":")[0] for c in issue_codes} | set(vocab_kinds)
    for cid, ch in CHAINS.items():
        score = sum(1 for t in ch["trigger"] if t in keys or t.split(":")[0] in keys)
        if score:
            out.append((score, cid))
    return [cid for _, cid in sorted(out, reverse=True)]


