def indicators_for(sym):
    """종목의 재료 지표 키 — 테마 지표 먼저, 그다음 업종 지표. 겹침 제거, 최대 MAX_INDICATORS 개."""
    out = []
    for g in groups(sym):
        out += THEME_INDICATORS.get(g, [])
    sec = sector(sym)
    if not (groups(sym) and sec in SECTOR_SKIP_IF_THEMED):
        out += SECTOR_INDICATORS.get(sec, [])
    seen, uniq = set(), []
    for k in out:
        if k not in seen:
            seen.add(k); uniq.append(k)
    return uniq[:MAX_INDICATORS]


